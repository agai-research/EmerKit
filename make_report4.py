"""Macros for the paper: A7 (Toucan trajectories), workflow-level calibration, fitted interference, clone-adjusted probes."""
import os, sys, glob, json
import numpy as np, pandas as pd
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE); sys.path.insert(0, os.path.join(HERE, "scripts"))
M = {}
def mac(k, v, pct=True, nd=1): M[k] = f"{100 * v:.{nd}f}" if pct else (f"{v:.{nd}f}" if isinstance(v, (float, np.floating)) else str(v))
for split, tag in [("warm", "Warm"), ("cold", "Cold")]:
    d = pd.read_csv(os.path.join(HERE, "results", "llm", f"A7_{split}.csv")); g = d.groupby("method").recall.mean()
    mac(f"Sv{tag}Traces", g["EmerKit (traces)"]); mac(f"Sv{tag}NoTraces", g["EmerKit (no traces)"]); mac(f"Sv{tag}Rag", g["RAG-MCP"]); mac(f"Sv{tag}Zeng", g["Zeng"])
    M[f"Sv{tag}N"] = str(d.trace.nunique())
tr = [json.loads(l) for l in open(os.path.join(HERE, "data", "traces", "toucan_traces.jsonl"))]
M["SvTraces"] = f"{len(tr):,}"; M["SvSuccess"] = f"{sum(t['success'] and bool(t['tools']) for t in tr):,}"
M["SvTools"] = str(len({x for t in tr for x in t["tools"]}))
w = pd.concat([pd.read_csv(f) for f in glob.glob(os.path.join(HERE, "results", "wf_calibration", "wfcal_seed*.csv"))]).groupby("calibration").mean(numeric_only=True)
for name, tag in [("workflow-level xi=0.05", "Wf"), ("task-level xi=0.05", "Task")]:
    mac(f"Wc{tag}Risk", w.loc[name, "workflow_risk"]); mac(f"Wc{tag}All", w.loc[name, "all_equipped"]); mac(f"Wc{tag}Eq", w.loc[name, "task_equipped"])
M["WcSeeds"] = str(len(glob.glob(os.path.join(HERE, "results", "wf_calibration", "wfcal_seed*.csv"))))
f = json.load(open(os.path.join(HERE, "config", "fitted_weights.json")))
M["FitAuc"] = f"{f['test_auc']:.2f}"; M["FitAucBase"] = f"{f['test_auc_without_interference']:.2f}"; M["FitLamC"] = f"{f['lam_C']:.3f}"
import run_probes_real as RP
from emerkit.prep import Prepared
T, rows = RP.design(); P = Prepared(T, RP.toucan_catalogue(0)[1], seed=0)
d = pd.concat([pd.read_csv(x) for x in glob.glob(os.path.join(HERE, "results", "llm", "A5real_*.csv"))]).reset_index(drop=True)
err = d[(d.correct == 0) & d.chosen.notna()]
clone = [T[int(t)]["name"] == T[int(c)]["name"] and P.desc_sim(int(t), int(c)) >= 0.95 for t, c in zip(err.target, err.chosen)]
mac("ClShare", np.mean(clone)); d["functional"] = d.correct; d.loc[err.index[np.array(clone)], "functional"] = 1
fa = d.groupby(["model", "confusable"]).functional.mean()
mac("ClHaiku", fa[("claude-haiku-5-5", 1)]); mac("ClOpus", fa[("claude-opus-5-5", 1)])
with open(os.path.join(HERE, "report", "macros4.tex"), "w") as fo:
    fo.write("% generated by make_report4.py\n" + "".join(f"\\newcommand{{\\R{k}}}{{{v}}}\n" for k, v in sorted(M.items())))
print(M)
